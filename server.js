app.get("/video/:filename", async (req, res) => {

    // Express already decodes route params (including a %2F
    // that was encoding a literal "/" within this single
    // segment) before handlers ever see them -- decoding again
    // here would be redundant at best, and would throw on any
    // filename containing a literal "%" character at worst.
    const filename =
        req.params.filename;

    // Containment: the decoded segment is attacker-controlled. Both
    // the source path and the derived cache path go through the shared
    // media-root guard -- a null result means it resolved outside its
    // root (traversal, absolute path, prefix sibling, symlink escape)
    // and is treated as "not present", identical to a genuine miss.
    const videoPath =
        resolveMediaFilePath(VIDEO_FOLDER, filename);


    // Look up whether this file was flagged during scanning as
    // needing a transcode. If it hasn't been scanned yet (no row,
    // or needs_transcode is still NULL), default to direct play --
    // matches the original behavior rather than blocking playback
    // on a probe that hasn't run yet. The lookup is unchanged: still
    // keyed on the raw relative_path exactly as stored by the scanner.
    const videoRow =
        db.prepare(`
            SELECT id, needs_transcode, video_codec, audio_codec, width, height, size
            FROM videos
            WHERE relative_path = ?
        `).get(filename);

    const needsTranscode =
        videoRow &&
        videoRow.needs_transcode === 1;

    const cachePath =
        videoRow
            ? resolveMediaFilePath(
                TRANSCODED_FOLDER,
                ffmpeg.getTranscodedRelativePath(filename)
            )
            : null;

    const cacheExists =
        cachePath !== null &&
        fs.existsSync(cachePath);

    const originalExists =
        videoPath !== null &&
        fs.existsSync(videoPath);


    // The original may have been moved out of videos/ (with
    // approval, once a converted copy exists -- see
    // /api/videos/:id/move-original above) -- that's fine as long
    // as the converted copy is there to serve instead. Only a
    // genuine "neither exists" is a 404.
    if (!originalExists && !cacheExists) {

        return res
            .status(404)
            .send("Video not found");

    }


    // --------------------------------------------------------
    // PLAYBACK DECISION -- Task 7 boundary + Task 8 Direct Play gate.
    //
    // probe -> capabilities -> decidePlayback, obtained ONLY through
    // playback-integration.js (no codec/container/capability rules
    // live here). When -- and only when -- the decision engine
    // EXPLICITLY returns DIRECT_PLAY, the request is routed onto the
    // hardened Task 3 serveDirectPlay() path for the original file.
    //
    // REMUX / AUDIO_TRANSCODE / VIDEO_TRANSCODE are NOT executed here:
    // any non-DIRECT_PLAY decision -- and any failure to decide --
    // falls through to the existing playback logic below, unchanged.
    //
    // Conservative rule (Task 6) is preserved: missing / unknown
    // capabilities never produce DIRECT_PLAY, so such a request takes
    // the existing safe fallback rather than a decision-gated direct
    // serve.
    // --------------------------------------------------------
    let playbackMode = null;
    let playbackBasis = "fallback";
    let playbackTarget = null;

    try {

        const resolved =
            await playbackIntegration.resolvePlaybackMode({
                filePath: videoPath || (cacheExists ? cachePath : null),
                row: videoRow,
                needsTranscode: needsTranscode,
                clientCapabilities:
                    playbackIntegration.readClientCapabilities(req)
            });

        playbackMode = resolved.mode;
        playbackBasis = resolved.basis;
        playbackTarget = resolved.target || null;

        if (playbackMode) {
            res.setHeader("X-Baseflix-Playback-Mode", playbackMode);
        }

    }
    catch (decisionError) {

        console.error(
            "Playback decision failed; using existing fallback:",
            decisionError.message
        );

    }


    // Task 8: the engine explicitly permits Direct Play -> serve the
    // ORIGINAL file through the hardened path. (If the original was
    // moved out and only a cache exists, fall through -- the existing
    // logic serves the cache.)
    if (playbackMode === "direct_play" && originalExists) {

        res.setHeader("X-Baseflix-Playback", "direct-play");
        res.setHeader("X-Baseflix-Playback-Basis", playbackBasis);

        return serveDirectPlay(videoPath, req, res);

    }


    // Task 9: the engine chose REMUX -> stream-copy the original into
    // the client-supported container Task 6 already picked, cache it,
    // and serve the COMPLETED file through the same hardened path (so
    // Range/206/416 all work). AUDIO_TRANSCODE / VIDEO_TRANSCODE are
    // NOT executed here -- they fall through to the existing logic.
    // If the remux fails or times out, the request falls back too;
    // it is never reported as a successful remux.
    if (playbackMode === "remux" && originalExists && playbackTarget) {

        const remuxAbort = new AbortController();
        res.on("close", () => remuxAbort.abort());

        let remuxResult = null;

        try {
            remuxResult =
                await remux.ensureRemux({
                    sourcePath: videoPath,
                    relativePath: filename,
                    container: playbackTarget,
                    signal: remuxAbort.signal
                });
        }
        catch (remuxError) {
            console.error(
                "Remux failed; using existing fallback:",
                remuxError && remuxError.message
            );
        }

        if (
            remuxResult && remuxResult.ok &&
            !res.writableEnded && !res.destroyed
        ) {
            res.setHeader("X-Baseflix-Playback", "remux");
            res.setHeader("X-Baseflix-Playback-Target", remuxResult.container);
            return serveDirectPlay(remuxResult.path, req, res);
        }

        // remux unavailable -> fall through to the existing behaviour
    }

    res.setHeader("X-Baseflix-Playback", "fallback");


    if (!needsTranscode) {

        // Non-transcoded files are never converted/cached, so the
        // original is the only copy -- if it's gone, there's
        // nothing else to serve.
        if (!originalExists) {

            return res
                .status(404)
                .send("Video not found");

        }

        return serveDirectPlay(videoPath, req, res);

    }


    // --------------------------------------------------------
    // ALREADY CACHED (from an earlier play, or the scanner's
    // background conversion)?
    // Serve the cached copy exactly like any other complete file,
    // seeking included. No need to pay the transcoding cost again
    // -- and this is the only option left if the original was
    // already deleted.
    // --------------------------------------------------------

    if (cacheExists) {

        return serveDirectPlay(cachePath, req, res);

    }


    if (!originalExists) {

        // Needs transcoding, no cache yet, and the original is
        // also gone -- genuinely nothing left to serve.
        return res
            .status(404)
            .send("Video not found");

    }


    // --------------------------------------------------------
    // LIVE TRANSCODE PATH
    // No range-request support on THIS request -- it's a single
    // live ffmpeg pipe, so seeking to an arbitrary timestamp isn't
    // possible yet. The output is simultaneously written to
    // TRANSCODED_FOLDER, though, so every future request for this
    // same file hits the cached-file branch above instead and
    // gets normal, fully-seekable playback.
    // --------------------------------------------------------

    // Re-derive which specific track(s) are the actual problem
    // from the codecs recorded during scanning (cheap -- no new
    // ffprobe call needed). Only re-encode the track(s) that
    // actually need it: re-encoding video you don't need to touch
    // is pure wasted CPU, and is a big part of why a transcode can
    // fail to keep up with real-time playback.
    const playability =
        ffmpeg.checkPlayability({
            videoCodec: videoRow.video_codec,
            audioCodec: videoRow.audio_codec
        });

    res.writeHead(200, {

        "Content-Type":
            "video/mp4"

        // Deliberately no Content-Length (unknown ahead of time)
        // and no Accept-Ranges (seeking isn't supported on this
        // particular request -- only on the cached file it
        // produces for next time).

    });


    let ffmpegProcess = null;


    // If the viewer closes the tab/player before the transcode
    // finishes, kill ffmpeg instead of leaving it running to
    // completion in the background.
    //
    // NOTE: this listens on the RESPONSE's close event, not the
    // request's. A bodyless GET request's own stream closes
    // almost immediately (there's no body to read), long before
    // the response finishes -- listening there would kill ffmpeg
    // right at the start of every single transcode. res.writableEnded
    // tells us whether this close is a normal finish or a real
    // early disconnect.
    res.on("close", () => {

        if (ffmpegProcess && !res.writableEnded) {

            ffmpegProcess.kill("SIGKILL");

        }

    });


    ffmpeg
        .transcodeToMp4Stream(
            videoPath,
            res,
            {
                copyVideo: playability.videoOk,
                copyAudio: playability.audioOk,
                maxHeight: MAX_TRANSCODE_HEIGHT,
                cacheFilePath: cachePath
            },
            (spawnedProcess) => {
                ffmpegProcess = spawnedProcess;
            }
        )
        .then((result) => {

            if (result && result.cachedComplete) {

                console.log(
                    `Cached transcode for future plays: ${filename}`
                );

            }

        })
        .catch((error) => {

            console.error(
                `Transcode failed for ${filename}:`,
                error.message
            );


            if (!res.headersSent) {

                res.status(500).end();

            }

            else {

                res.end();

            }

        });

});


