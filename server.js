// PENDING CLEANUP
// Videos the scanner has fully converted to a high-quality
// browser-compatible copy, where the original is still sitting
// in videos/ awaiting a keep/move decision.
// ============================================================

app.get("/api/videos/pending-cleanup", (req, res) => {

    try {

        const rows =
            db.prepare(`
                SELECT id, name, relative_path, size
                FROM videos
                WHERE original_status = 'pending'
            `).all();


        const pending =
            rows
                .map((row) => {

                    const originalPath =
                        path.join(
                            VIDEO_FOLDER,
                            row.relative_path
                        );

                    const cachePath =
                        path.join(
                            TRANSCODED_FOLDER,
                            ffmpeg.getTranscodedRelativePath(row.relative_path)
                        );


                    // Defensive: only ever surface this as
                    // "ready to decide on" if the converted copy
                    // genuinely exists AND the original is still
                    // in videos/ to be moved. Anything else is a
                    // weird intermediate state -- skip it rather
                    // than risk pointing the UI at something
                    // unsafe to act on.
                    if (
                        !fs.existsSync(cachePath) ||
                        !fs.existsSync(originalPath)
                    ) {

                        return null;

                    }


                    const convertedSize =
                        fs.statSync(cachePath).size;


                    return {
                        id: row.id,
                        name: row.name,
                        relative_path: row.relative_path,
                        original_size: row.size,
                        converted_size: convertedSize
                    };

                })
                .filter(item => item !== null);


        res.json(pending);

    }

    catch (error) {

        console.error(
            "Could not load pending cleanup list:",
            error
        );

        res
            .status(500)
            .json({
                error:
                    "Could not load pending cleanup list"
            });

    }

});


// ============================================================
// MOVE AN ORIGINAL FILE OUT OF videos/
// Non-destructive -- the file is relocated to
// NOT_COMPATIBLE_FOLDER (preserving its subfolder structure),
// never deleted. Still admin-gated since it does restructure
// the filesystem, but nothing is ever permanently lost.
// ============================================================

// ============================================================
// MOVE-WITH-FALLBACK HELPER
// A plain rename() fails with EXDEV if source and destination
// are on different drives/filesystems -- falls back to
// copy-then-remove, which works across drives. Shared by both
// the "move the original out" and "move the converted copy in"
// steps below.
// ============================================================

function moveFileWithFallback(sourcePath, destinationPath) {

    fs.mkdirSync(
        path.dirname(destinationPath),
        { recursive: true }
    );

    try {

        fs.renameSync(sourcePath, destinationPath);

    }

    catch (moveError) {

        if (moveError.code === "EXDEV") {

            fs.copyFileSync(sourcePath, destinationPath);

            fs.unlinkSync(sourcePath);

        }

        else {

            throw moveError;

        }

    }

}


app.post(
    "/api/videos/:id/move-original",
    checkAdmin,
    async (req, res) => {

        try {

            const id =
                Number(req.params.id);

            if (!Number.isInteger(id)) {

                return res
                    .status(400)
                    .json({
                        error:
                            "Invalid video ID"
                    });

            }


            const row =
                db.prepare(`
                    SELECT id, relative_path, original_status
                    FROM videos
                    WHERE id = ?
                `).get(id);

            if (!row) {

                return res
                    .status(404)
                    .json({
                        error:
                            "Video not found"
                    });

            }


            const cachePath =
                path.join(
                    TRANSCODED_FOLDER,
                    ffmpeg.getTranscodedRelativePath(row.relative_path)
                );

            // Never move an original unless a working converted
            // copy genuinely exists on disk right now -- refuse
            // even if the DB row claims status is 'pending'.
            if (!fs.existsSync(cachePath)) {

                return res
                    .status(409)
                    .json({
                        error:
                            "No converted copy exists yet -- refusing to move the original"
                    });

            }


            const originalPath =
                path.join(
                    VIDEO_FOLDER,
                    row.relative_path
                );

            const archivePath =
                path.join(
                    NOT_COMPATIBLE_FOLDER,
                    row.relative_path
                );

            // Where the converted copy will end up living --
            // the EXACT same folder the original just vacated,
            // just with a .mp4 extension (the real container
            // format now). This is what makes it show up right
            // next to where the user expects it, instead of in a
            // separate parallel folder tree.
            const newRelativePath =
                ffmpeg.getTranscodedRelativePath(row.relative_path);

            const newVideoPath =
                path.join(VIDEO_FOLDER, newRelativePath);


            if (fs.existsSync(originalPath)) {

                moveFileWithFallback(
                    originalPath,
                    archivePath
                );

            }


            // Defensive: only possible if some unrelated file
            // already happened to occupy this exact spot -- the
            // original's own path was just vacated above, so this
            // is not that file. Refuse rather than risk silently
            // overwriting something else's data.
            if (fs.existsSync(newVideoPath)) {

                return res
                    .status(409)
                    .json({
                        error:
                            "A file already exists at the destination path -- " +
                            "the original was archived, but the converted copy " +
                            "was not moved into place. Please resolve the " +
                            "conflict manually."
                    });

            }


            moveFileWithFallback(
                cachePath,
                newVideoPath
            );


            // Re-probe the file in its new permanent home so the
            // database accurately reflects its real codecs/
            // dimensions/duration, rather than guessing.
            const probeResult =
                await ffmpeg.probeFile(newVideoPath);


            db.prepare(`
                UPDATE videos
                SET
                    relative_path = ?,
                    name = ?,
                    needs_transcode = 0,
                    video_codec = ?,
                    audio_codec = ?,
                    duration = ?,
                    width = ?,
                    height = ?,
                    original_status = 'moved'
                WHERE id = ?
            `).run(
                newRelativePath,
                path.basename(newRelativePath),
                probeResult ? probeResult.videoCodec : null,
                probeResult ? probeResult.audioCodec : null,
                probeResult ? probeResult.duration : null,
                probeResult ? probeResult.width : null,
                probeResult ? probeResult.height : null,
                id
            );


            res.json({
                success: true,
                original_archived_to: archivePath,
                video_now_at: newVideoPath
            });

        }

        catch (error) {

            console.error(
                "Could not move original file:",
                error
            );

            res
                .status(500)
                .json({
                    error:
                        "Could not move original file"
                });

        }

    }
);


