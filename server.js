// Minimal HTML-escaping so a crafted filename can't break out
// of the page (defense in depth — these are your own files,
// but cheap to guard against anyway).
function escapeHtml(text) {

    return String(text)
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;");

}


