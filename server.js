// SAVE CONTINUE WATCHING
// ============================================================

app.post(
    "/api/continue-watching",
    (req, res) => {

        try {

            const {
                profileId,
                videoId,
                position,
                duration
            } = req.body;


            if (
                !Number.isInteger(
                    Number(profileId)
                ) ||
                !Number.isInteger(
                    Number(videoId)
                )
            ) {

                return res
                    .status(400)
                    .json({
                        error:
                            "Invalid profile or video ID"
                    });

            }


            const cleanProfileId =
                Number(
                    profileId
                );


            const cleanVideoId =
                Number(
                    videoId
                );


            const cleanPosition =
                Number(
                    position
                );


            const cleanDuration =
                Number(
                    duration
                );


            if (
                !Number.isFinite(
                    cleanPosition
                ) ||
                !Number.isFinite(
                    cleanDuration
                )
            ) {

                return res
                    .status(400)
                    .json({
                        error:
                            "Invalid playback position"
                    });

            }


            // ----------------------------------------------------
            // REJECT NONSENSICAL VALUES
            // A negative position, a zero/negative duration, or
            // a position past the end of the video should never
            // be written to the database.
            // ----------------------------------------------------

            if (
                cleanPosition < 0 ||
                cleanDuration <= 0
            ) {

                return res
                    .status(400)
                    .json({
                        error:
                            "Position and duration must be positive"
                    });

            }


            // Clamp instead of rejecting: players sometimes report
            // a position a fraction of a second past duration due
            // to float rounding right at the end of playback.
            const safePosition =
                Math.min(
                    cleanPosition,
                    cleanDuration
                );


            // ----------------------------------------------------
            // VERIFY PROFILE EXISTS
            // ----------------------------------------------------

            const profile =
                db.prepare(`
                    SELECT
                        id
                    FROM profiles
                    WHERE id = ?
                `).get(
                    cleanProfileId
                );


            if (!profile) {

                return res
                    .status(404)
                    .json({
                        error:
                            "Profile not found"
                    });

            }


            // ----------------------------------------------------
            // VERIFY VIDEO EXISTS
            // ----------------------------------------------------

            const video =
                db.prepare(`
                    SELECT
                        id
                    FROM videos
                    WHERE id = ?
                `).get(
                    cleanVideoId
                );


            if (!video) {

                return res
                    .status(404)
                    .json({
                        error:
                            "Video not found"
                    });

            }


            // ----------------------------------------------------
            // JUST STARTED OR FINISHED -> DON'T KEEP A ROW
            // Same thresholds the GET endpoint uses to hide these
            // entries. Deleting here (instead of only filtering on
            // read) means the table never accumulates dead rows for
            // videos that are done or barely begun.
            // ----------------------------------------------------

            const isJustStarted =
                safePosition <= START_BUFFER_SECONDS;

            const isFinished =
                safePosition >=
                cleanDuration - END_BUFFER_SECONDS;


            if (isJustStarted || isFinished) {

                db.prepare(`
                    DELETE FROM continue_watching
                    WHERE profile_id = ?
                    AND video_id = ?
                `).run(
                    cleanProfileId,
                    cleanVideoId
                );


                // Only a genuine finish counts as "watched" --
                // not a reset from barely starting it.
                if (isFinished) {

                    db.prepare(`
                        INSERT INTO watch_history
                        (
                            profile_id,
                            video_id,
                            watched_at
                        )

                        VALUES
                        (
                            ?,
                            ?,
                            CURRENT_TIMESTAMP
                        )

                        ON CONFLICT (
                            profile_id,
                            video_id
                        )

                        DO UPDATE SET

                            watched_at =
                                CURRENT_TIMESTAMP

                    `).run(
                        cleanProfileId,
                        cleanVideoId
                    );

                }


                return res.json({
                    success: true,
                    tracked: false
                });

            }


            // ----------------------------------------------------
            // SAVE / UPDATE PROGRESS
            // ----------------------------------------------------

            db.prepare(`
                INSERT INTO continue_watching
                (
                    profile_id,
                    video_id,
                    position,
                    duration,
                    updated_at
                )

                VALUES
                (
                    ?,
                    ?,
                    ?,
                    ?,
                    CURRENT_TIMESTAMP
                )

                ON CONFLICT (
                    profile_id,
                    video_id
                )

                DO UPDATE SET

                    position =
                        excluded.position,

                    duration =
                        excluded.duration,

                    updated_at =
                        CURRENT_TIMESTAMP

            `).run(

                cleanProfileId,

                cleanVideoId,

                safePosition,

                cleanDuration

            );


            res.json({
                success: true,
                tracked: true
            });

        }

        catch (error) {

            console.error(
                "Could not save Continue Watching:",
                error
            );


            res
                .status(500)
                .json({
                    error:
                        "Could not save Continue Watching"
                });

        }

    }
);


