// Verify a password (the "log in as Admin" check). Returns
// success so the frontend can unlock admin mode for the session.
// The frontend then reuses the same password as x-admin-key.
app.post("/api/admin/login", (req, res) => {

    try {

        const { password } =
            req.body;

        const storedHash =
            getStoredAdminHash();

        if (!storedHash) {

            return res
                .status(400)
                .json({
                    error: "no_admin_password_set"
                });

        }

        if (!password || !verifyPassword(password, storedHash)) {

            return res
                .status(401)
                .json({
                    error: "Incorrect password."
                });

        }

        res.json({ success: true });

    }

    catch (error) {

        console.error("Admin login error:", error);

        res
            .status(500)
            .json({ error: "Could not verify password" });

    }

});


// Set the admin password. On FIRST setup (no password yet) this
// is open, so a fresh install can bootstrap. To CHANGE an existing
// password, the current one must be supplied and correct.
app.post("/api/admin/set-password", (req, res) => {

    try {

        const { newPassword, currentPassword } =
            req.body;

        if (!newPassword || newPassword.length < 4) {

            return res
                .status(400)
                .json({
                    error:
                        "Password must be at least 4 characters."
                });

        }


        const storedHash =
            getStoredAdminHash();

        // Changing an existing password requires the current one.
        if (storedHash) {

            if (
                !currentPassword ||
                !verifyPassword(currentPassword, storedHash)
            ) {

                return res
                    .status(403)
                    .json({
                        error:
                            "Current password is incorrect."
                    });

            }

        }


        const newHash =
            hashPassword(newPassword);

        db.prepare(`
            INSERT INTO settings (key, value)
            VALUES ('admin_password_hash', ?)
            ON CONFLICT (key)
            DO UPDATE SET value = excluded.value
        `).run(newHash);


        res.json({ success: true });

    }

    catch (error) {

        console.error("Set admin password error:", error);

        res
            .status(500)
            .json({ error: "Could not set password" });

    }

});


