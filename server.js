function checkAdmin(req, res, next) {

    const storedHash =
        getStoredAdminHash();

    // No password set up yet -- fall back to the env var if one's
    // configured (keeps existing installs working), otherwise the
    // very first password-set call is allowed through by its own
    // endpoint, not here.
    if (!storedHash) {

        const envKey =
            process.env.BASEFLIX_ADMIN_KEY;

        if (envKey && req.headers["x-admin-key"] === envKey) {

            return next();

        }

        return res
            .status(403)
            .json({
                error:
                    "no_admin_password_set"
            });

    }


    const suppliedKey =
        req.headers["x-admin-key"];

    if (
        !suppliedKey ||
        !verifyPassword(suppliedKey, storedHash)
    ) {

        return res
            .status(403)
            .json({
                error:
                    "Admin access required"
            });

    }


    next();

}


