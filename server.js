// ============================================================
// ADMIN PASSWORD
// The Admin profile's password IS the admin credential -- there's
// no separate key. It's stored as a salted scrypt hash in the
// settings table (never plaintext, never an env var), and every
// privileged request sends the raw password as x-admin-key, which
// checkAdmin verifies against the stored hash.
//
// This is basic access control for a personal home server, not a
// hardened auth system -- appropriate for keeping non-admin
// profiles (or a guest) out of admin controls.
// ============================================================

function hashPassword(password) {

    // 16-byte random salt, scrypt, stored as "salt:hash" hex.
    const salt =
        crypto.randomBytes(16).toString("hex");

    const derived =
        crypto.scryptSync(password, salt, 64).toString("hex");

    return `${salt}:${derived}`;

}

function verifyPassword(password, stored) {

    if (!stored || !stored.includes(":")) {

        return false;

    }

    const [salt, originalHash] =
        stored.split(":");

    const derived =
        crypto.scryptSync(password, salt, 64).toString("hex");

    // Constant-time comparison to avoid leaking timing info.
    const a =
        Buffer.from(originalHash, "hex");

    const b =
        Buffer.from(derived, "hex");

    return (
        a.length === b.length &&
        crypto.timingSafeEqual(a, b)
    );

}

function getStoredAdminHash() {

    const row =
        db.prepare(`
            SELECT value
            FROM settings
            WHERE key = 'admin_password_hash'
        `).get();

    return row ? row.value : null;

}

function isAdminPasswordSet() {

    return !!getStoredAdminHash();

}


