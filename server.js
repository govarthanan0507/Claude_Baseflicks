// ============================================================
// BULK POPULATE FROM THE WEB
// Runs populateVideoFromWeb across every video that doesn't
// already have a custom_title (i.e. hasn't been identified yet --
// this never overwrites something already fetched or manually
// entered). Processes one video at a time, in the background, the
// same sequential pattern the scanner's own background conversion
// queue already uses -- never in parallel, since each populate
// call is itself several TMDB requests. The response returns
// immediately; progress is polled via the status endpoint below.
// ============================================================

let bulkPopulateStatus = {
    running: false,
    total: 0,
    completed: 0,
    succeeded: 0,
    failed: 0,
    currentVideo: null,
    errors: [],
    stoppedReason: null
};

app.post(
    "/api/bulk-populate-from-web",
    checkAdmin,
    (req, res) => {

        if (bulkPopulateStatus.running) {

            return res
                .status(409)
                .json({
                    error:
                        "A bulk populate is already running."
                });

        }


        const rows =
            db.prepare(`
                SELECT id, name
                FROM videos
                WHERE custom_title IS NULL
                ORDER BY folder, name
            `).all();

        bulkPopulateStatus = {
            running: true,
            total: rows.length,
            completed: 0,
            succeeded: 0,
            failed: 0,
            currentVideo: null,
            errors: [],
            stoppedReason: null
        };


        res.json({
            started: true,
            total: rows.length
        });


        // Fire-and-forget -- the response above has already been
        // sent, this runs on its own after that.
        (async () => {

            const MAX_CONSECUTIVE_FAILURES = 3;

            let consecutiveFailures = 0;

            for (const row of rows) {

                bulkPopulateStatus.currentVideo =
                    row.name;

                try {

                    const result =
                        await populateVideoFromWeb(row.id);

                    if (result.success) {

                        bulkPopulateStatus.succeeded++;

                        consecutiveFailures = 0;

                    }

                    else {

                        bulkPopulateStatus.failed++;

                        bulkPopulateStatus.errors.push({
                            videoId: row.id,
                            name: row.name,
                            error: result.error
                        });

                        // No API key configured -- every remaining
                        // video would fail the exact same way, so
                        // stop immediately rather than burning
                        // through the whole list pointlessly.
                        if (result.error === "no_api_key") {

                            bulkPopulateStatus.stoppedReason =
                                "No TMDB API key is configured.";

                            break;

                        }

                        consecutiveFailures++;

                        if (consecutiveFailures >= MAX_CONSECUTIVE_FAILURES) {

                            bulkPopulateStatus.stoppedReason =
                                `Stopped after ${MAX_CONSECUTIVE_FAILURES} ` +
                                `failures in a row: ${result.error}`;

                            break;

                        }

                    }

                }

                catch (error) {

                    console.error(
                        "Bulk populate error for video",
                        row.id,
                        error
                    );

                    bulkPopulateStatus.failed++;

                    bulkPopulateStatus.errors.push({
                        videoId: row.id,
                        name: row.name,
                        error: "Unexpected error"
                    });

                    consecutiveFailures++;

                    if (consecutiveFailures >= MAX_CONSECUTIVE_FAILURES) {

                        bulkPopulateStatus.stoppedReason =
                            `Stopped after ${MAX_CONSECUTIVE_FAILURES} ` +
                            `failures in a row.`;

                        break;

                    }

                }

                bulkPopulateStatus.completed++;

                // A small courtesy delay between requests, so a
                // big library doesn't hammer TMDB back-to-back and
                // trigger rate limiting in the first place.
                await new Promise(resolve => setTimeout(resolve, 300));

            }

            bulkPopulateStatus.running = false;

            bulkPopulateStatus.currentVideo = null;

        })();

    }
);


app.get(
    "/api/bulk-populate-status",
    (req, res) => {

        res.json(bulkPopulateStatus);

    }
);


