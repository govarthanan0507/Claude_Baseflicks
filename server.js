// APPLY A CHOSEN TMDB MATCH
// Fetches full details for a SPECIFIC, already-known TMDB movie
// id -- no searching involved -- and saves them, the same way
// populate-from-web does. Used once the person has picked which
// search result is actually correct.
// ============================================================

app.post(
    "/api/videos/:id/apply-tmdb-match",
    checkAdmin,
    async (req, res) => {

        try {

            const id =
                Number(req.params.id);

            if (!Number.isInteger(id)) {

                return res
                    .status(400)
                    .json({
                        error:
                            "Invalid video ID"
                    });

            }

            const tmdbId =
                Number(req.body.tmdbId);

            if (!Number.isInteger(tmdbId)) {

                return res
                    .status(400)
                    .json({
                        error:
                            "Invalid TMDB id"
                    });

            }


            const row =
                db.prepare(`
                    SELECT name, custom_title, folder
                    FROM videos
                    WHERE id = ?
                `).get(id);

            if (!row) {

                return res
                    .status(404)
                    .json({
                        error:
                            "Video not found"
                    });

            }


            const episode =
                isEpisodeFolder(row.folder);

            let metadata;

            if (episode) {

                const seasonEpisode =
                    poster.extractSeasonEpisode(row.name);

                if (!seasonEpisode) {

                    return res
                        .status(422)
                        .json({
                            error:
                                `Could not find a season/episode number ` +
                                `(like "S01E02") in "${row.name}".`
                        });

                }

                // Here tmdbId is the SHOW's id (that's what the
                // search results list contains for episodes) --
                // the specific episode still comes from the
                // video's own filename, not from the search pick.
                metadata =
                    await poster.fetchFullEpisodeDetails(
                        tmdbId,
                        seasonEpisode.season,
                        seasonEpisode.episode,
                        row.custom_title || row.name
                    );

            }

            else {

                metadata =
                    await poster.fetchFullMovieDetails(
                        tmdbId,
                        row.custom_title || row.name
                    );

            }

            if (metadata && metadata.error === "no_api_key") {

                return res
                    .status(400)
                    .json({
                        error: "no_api_key"
                    });

            }

            if (metadata && metadata.error) {

                return res
                    .status(502)
                    .json({
                        error: metadata.error
                    });

            }

            if (!metadata) {

                return res
                    .status(404)
                    .json({
                        error:
                            "Could not fetch details for that match."
                    });

            }


            if (episode) {

                db.prepare(`
                    UPDATE videos
                    SET
                        custom_title = ?,
                        overview = ?,
                        custom_date = ?,
                        genres = ?,
                        poster = COALESCE(?, poster)
                    WHERE id = ?
                `).run(
                    metadata.title,
                    metadata.overview,
                    metadata.date,
                    metadata.genres,
                    metadata.poster,
                    id
                );

            }

            else {

                db.prepare(`
                    UPDATE videos
                    SET
                        custom_title = ?,
                        overview = ?,
                        release_year = ?,
                        genres = ?,
                        poster = COALESCE(?, poster),
                        tagline = ?,
                        studio = ?,
                        director = ?,
                        writers = ?,
                        backdrop = COALESCE(?, backdrop),
                        landscape = COALESCE(?, landscape),
                        logo = COALESCE(?, logo)
                    WHERE id = ?
                `).run(
                    metadata.title,
                    metadata.overview,
                    metadata.year,
                    metadata.genres,
                    metadata.poster,
                    metadata.tagline,
                    metadata.studio,
                    metadata.director,
                    metadata.writers,
                    metadata.backdrop,
                    metadata.landscape,
                    metadata.logo,
                    id
                );

            }


            res.json({
                success: true,
                metadata: metadata
            });

        }

        catch (error) {

            console.error(
                "Could not apply TMDB match:",
                error
            );

            res
                .status(500)
                .json({
                    error:
                        "Could not apply TMDB match"
                });

        }

    }
);


