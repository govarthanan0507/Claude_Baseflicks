// Fetches just the basics -- title, overview, year, genres, and
// (if we don't already have a better one) a real poster. Doesn't
// touch relative_path/name. Admin-gated, same as manual editing.
// Shared between the single-video endpoint below and the bulk
// "populate the whole library" background job further down.
// ============================================================

async function populateVideoFromWeb(id) {

    const row =
        db.prepare(`
            SELECT name, custom_title, folder
            FROM videos
            WHERE id = ?
        `).get(id);

    if (!row) {

        return { success: false, status: 404, error: "Video not found" };

    }


    const resolved =
        await poster.resolveVideoMetadata(row);

    if (resolved.error) {

        return {
            success: false,
            status: resolved.status,
            error: resolved.error
        };

    }


    writeMetadataToVideo(id, row.folder, resolved.metadata);


    return { success: true, metadata: resolved.metadata };

}


