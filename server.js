// ============================================================
// WATCH STATUS FOR SPECIFIC VIDEOS
// Unlike /api/watch-history (capped at 10, most-recent-only),
// this checks exactly the video IDs the caller asks about --
// used by the episode list so a completed episode from a while
// back still correctly shows as completed, not just "not started".
// ============================================================

app.get(
    "/api/watch-status/:profileId",
    (req, res) => {

        try {

            const profileId =
                Number(req.params.profileId);

            if (!Number.isInteger(profileId)) {

                return res
                    .status(400)
                    .json({
                        error:
                            "Invalid profile ID"
                    });

            }


            const videoIds =
                (req.query.videoIds || "")
                    .split(",")
                    .map(Number)
                    .filter(Number.isInteger);

            if (videoIds.length === 0) {

                return res.json({});

            }


            const placeholders =
                videoIds.map(() => "?").join(",");


            const inProgressRows =
                db.prepare(`
                    SELECT video_id, position, duration
                    FROM continue_watching
                    WHERE profile_id = ?
                    AND video_id IN (${placeholders})
                `).all(profileId, ...videoIds);

            const completedRows =
                db.prepare(`
                    SELECT video_id, watched_at
                    FROM watch_history
                    WHERE profile_id = ?
                    AND video_id IN (${placeholders})
                `).all(profileId, ...videoIds);


            const status = {};

            for (const row of inProgressRows) {

                status[row.video_id] = {
                    status: "in_progress",
                    position: row.position,
                    duration: row.duration
                };

            }

            for (const row of completedRows) {

                // In-progress takes precedence if a video somehow
                // has rows in both (shouldn't normally happen,
                // since they're mutually exclusive by design).
                if (!status[row.video_id]) {

                    status[row.video_id] = {
                        status: "completed"
                    };

                }

            }


            res.json(status);

        }

        catch (error) {

            console.error(
                "Could not load watch status:",
                error
            );

            res
                .status(500)
                .json({
                    error:
                        "Could not load watch status"
                });

        }

    }
);


